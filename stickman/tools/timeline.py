#!/usr/bin/env python3
"""Lay VO segments (seg0..N.wav) on a timeline and write vo/timing.js + vo/voiceover.wav.
Usage: timeline.py <vo_dir> [--gap 0.45] [--start 0.3] [--tail 1.0] [--extra 4:0.8,11:0.8 ...]
--extra i:sec adds extra silence BEFORE segment i (section breaks). --tail = silence after the last line.
timing.js defines SEG = [{s: start, d: duration, ph: [phrase start times]}], DURATION.
"""
import sys, subprocess, re, json, os, glob
args = sys.argv[1:]; d = args[0]
opt = lambda k, v: (args[args.index(k) + 1] if k in args else v)
gap, start, tail = float(opt('--gap', .45)), float(opt('--start', .3)), float(opt('--tail', 1.0))
extra = {int(a): float(b) for a, b in (x.split(':') for x in opt('--extra', '').split(',') if x)}
os.chdir(d)
n = len(glob.glob('seg*.wav'))
segs, t = [], start
for i in range(n):
    f = f'seg{i}.wav'
    dur = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).decode())
    log = subprocess.run(['ffmpeg', '-nostdin', '-i', f, '-af', 'silencedetect=n=-38dB:d=0.18', '-f', 'null', '-'], capture_output=True, text=True).stderr
    ends = [float(x) for x in re.findall(r'silence_end: ([0-9.]+)', log)]
    t += extra.get(i, 0)
    segs.append({'s': round(t, 3), 'd': round(dur, 3), 'ph': [round(t, 3)] + [round(t + e, 3) for e in ends if e < dur - .1]})
    t += dur + gap
total = round(t - gap + tail, 2)
open('timing.js', 'w').write('// generated by tools/timeline.py\nconst SEG = ' + json.dumps(segs) + ';\nconst VO_DURATION = ' + str(total) + ';\n')
# mix
inputs, flt, mix = [], '', ''
for i, sg in enumerate(segs):
    inputs += ['-i', f'seg{i}.wav']; ms = int(sg['s'] * 1000)
    flt += f'[{i}:a]adelay={ms}|{ms}[a{i}];'; mix += f'[a{i}]'
chain = (f"{flt}{mix}amix=inputs={n}:normalize=0,highpass=f=70,equalizer=f=180:t=q:w=1:g=2,equalizer=f=3500:t=q:w=1.5:g=2,"
         f"acompressor=threshold=-20dB:ratio=3:attack=5:release=120,apad=whole_dur={total},atrim=0:{total},loudnorm=I=-14:TP=-1.5:LRA=9")
subprocess.run(['ffmpeg', '-nostdin', '-loglevel', 'error', '-y', *inputs, '-filter_complex', chain, '-ar', '44100', '-ac', '2', 'voiceover.wav'], check=True)
print(f'{n} segments, VO duration {total}s -> timing.js, voiceover.wav')
